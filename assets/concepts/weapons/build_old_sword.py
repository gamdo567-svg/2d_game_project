"""시작 무기 '낡은 검' 그림 (assets/images/player/weapons/old_sword.png)을 도트로 찍는다.

기준: 컨셉 시트(player_character_concept_v1.png) 왼쪽 아래 '기본 무기 - 낡은 검'.
- 연한 은회색 칼날(위 밝은 면, 아래 어두운 날), 녹 얼룩, 비스듬히 깎인 칼끝
- 넓은 금색 십자 가드(양 끝 둥근 장식), 갈색 감긴 손잡이, 둥근 금색 손잡이 끝
게임 규격: 56×10, 칼끝이 오른쪽(0도), 손(주먹)이 그림 한가운데(28, 5). 게임이 손 위치·각도에 맞춰 돌려 그린다.
Pillow 필요(게임 실행에는 필요 없음). 사용: 저장소 루트에서 `python assets/concepts/weapons/build_old_sword.py`
"""
import os

from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
OUT = os.path.join(ROOT, 'assets', 'images', 'player', 'weapons', 'old_sword.png')

COLORS = {
    'O': (0x16, 0x0F, 0x14),  # 외곽선 (게임 외곽선 계열)
    'L': (0xDB, 0xCC, 0xC5),  # 칼날 밝은 면
    'W': (0xE9, 0xDC, 0xD2),  # 칼날 반짝임
    'M': (0xB2, 0x9A, 0x95),  # 칼날 중간
    'D': (0x71, 0x53, 0x59),  # 칼날 어두운 날
    'R': (0xB2, 0x8F, 0x78),  # 녹
    'G': (0xD5, 0x99, 0x67),  # 금색 가드
    'g': (0xA5, 0x65, 0x3F),  # 금색 어두운 쪽
    'H': (0xF8, 0xD9, 0xA4),  # 금색 반짝임
    'B': (0x8B, 0x5F, 0x41),  # 손잡이 가죽
    'b': (0x5C, 0x30, 0x2D),  # 손잡이 감은 줄
    'F': (0x30, 0x1E, 0x25),  # 장갑 낀 주먹 (Idle 장갑 색)
}

# 56×10. 손(주먹)은 27·28열, 4·5행 (그림 한가운데). 칼끝은 오른쪽. 손에서 칼끝까지 23픽셀.
# 기준 그림 비율: 칼날이 손잡이보다 넓고(3픽셀) 전체 길이의 약 60%, 가드는 얇고 길며(1열 × 8행), 둥근 손잡이 끝.
# 아래 그리기 명령으로 칸을 채운다: (x0, x1, y, 글자) = x0~x1 열의 y 행.
BLADE_STROKES = [
    # 칼날 (31~49열): 3행 밝은 면, 4행 가운데(녹 얼룩), 5행 어두운 날. 칼끝은 4행이 가장 길다 (뾰족)
    (31, 48, 3, 'L'), (33, 36, 3, 'W'), (31, 49, 4, 'M'), (38, 38, 4, 'R'), (44, 44, 4, 'R'), (31, 48, 5, 'D'),
    (41, 41, 5, 'R'),
    (49, 50, 3, 'O'), (50, 50, 4, 'L'), (51, 51, 4, 'O'), (49, 50, 5, 'O'),
    (31, 48, 2, 'O'), (31, 49, 6, 'O'),
]
# 손잡이 쪽: 두 손 잡기 (2026-11-17). 오른손은 가드 바로 아래(27·28열, 그림 한가운데),
# 왼손은 그 뒤(23~25열 근처). 주먹은 게임에서 몸 그림과 오른손 레이어가 그리므로 칼 그림에는 넣지 않는다.
HILT_STROKES = [
    # 가드 (30열, 1~8행): 얇고 긴 금색 십자 가드, 양 끝 둥근 장식(밝은 금), 가운데 반짝임
    (30, 30, 1, 'H'), (30, 30, 2, 'G'), (30, 30, 3, 'G'), (30, 30, 4, 'H'), (30, 30, 5, 'G'), (30, 30, 6, 'g'),
    (30, 30, 7, 'g'), (30, 30, 8, 'H'),
    (30, 30, 0, 'O'), (30, 30, 9, 'O'), (29, 29, 1, 'O'), (29, 29, 2, 'O'), (29, 29, 3, 'O'), (29, 29, 6, 'O'),
    (29, 29, 7, 'O'), (29, 29, 8, 'O'), (31, 31, 1, 'O'), (31, 31, 7, 'O'), (31, 31, 8, 'O'),
    # 손잡이 (22~29열, 4·5행): 갈색 가죽에 감은 줄 (두 손이 들어가는 길이)
] + [(x, x, 4, 'B' if x % 2 else 'b') for x in range(22, 30)] + [(x, x, 5, 'b' if x % 2 else 'B') for x in range(22, 30)] + [
    (22, 28, 3, 'O'), (22, 28, 6, 'O'),
    # 둥근 금색 손잡이 끝 (19~21열, 3~6행)
    (20, 20, 3, 'G'), (19, 19, 4, 'G'), (20, 20, 4, 'H'), (21, 21, 4, 'G'), (19, 19, 5, 'g'), (20, 20, 5, 'G'),
    (21, 21, 5, 'g'), (20, 20, 6, 'g'),
    (20, 20, 2, 'O'), (19, 19, 3, 'O'), (21, 21, 3, 'O'), (18, 18, 4, 'O'), (18, 18, 5, 'O'), (19, 19, 6, 'O'),
    (21, 21, 6, 'O'), (20, 20, 7, 'O'),
]
STROKES = BLADE_STROKES + HILT_STROKES
WIDTH, HEIGHT = 56, 10


def main():
    img = Image.new('RGBA', (WIDTH, HEIGHT), (0, 0, 0, 0))
    for x0, x1, y, ch in STROKES:
        for x in range(x0, x1 + 1):
            img.putpixel((x, y), COLORS[ch] + (255,))
    img.save(OUT)
    img.resize((WIDTH * 10, HEIGHT * 10), Image.NEAREST).save(os.path.join(os.path.dirname(__file__), 'old_sword_x10.png'))


if __name__ == '__main__':
    main()
